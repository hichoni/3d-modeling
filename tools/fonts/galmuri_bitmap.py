"""Pack Galmuri11's Hangul bitmaps for the booth's pixel font (픽셀).

Galmuri (https://github.com/quiple/galmuri, SIL OFL 1.1, no Reserved Font Name) is a Korean pixel font drawn on an
11 x 11 grid. This reads its BDF and writes every Hangul syllable (U+AC00-D7A3) and compatibility jamo (U+3131-3163)
as 11 rows of 11-bit masks, base64 of little-endian uint16.

    npm pack galmuri@2.40.3 && tar xzf galmuri-2.40.3.tgz
    python3 tools/fonts/galmuri_bitmap.py package/dist/Galmuri11.bdf vendor/galmuri/galmuri11-hangul.js
"""
import base64, struct, sys

ROWS, COLS = 11, 11
RANGES = [(0xAC00, 0xD7A3), (0x3131, 0x3163)]


def glyphs(path):
    lines = open(path, encoding='utf-8').read().split('\n'); out = {}; i = 0
    while i < len(lines):
        if lines[i].startswith('ENCODING '):
            cp = int(lines[i].split()[1]); j = i
            while not lines[j].startswith('BBX'): j += 1
            w, h, ox, oy = map(int, lines[j].split()[1:])
            while lines[j] != 'BITMAP': j += 1
            out[cp] = (w, h, ox, oy, lines[j + 1:j + 1 + h]); i = j
        i += 1
    return out


def pack(g):
    w, h, ox, oy, rows = g; top = ROWS - h - oy; grid = [0] * ROWS
    for r, hexrow in enumerate(rows):
        bits = bin(int(hexrow, 16))[2:].zfill(len(hexrow) * 4)[:w]
        for c, b in enumerate(bits):
            if b == '1' and 0 <= top + r < ROWS and 0 <= ox + c < COLS: grid[top + r] |= 1 << (ox + c)
    return grid


if __name__ == '__main__':
    src, dst = sys.argv[1:3]; g = glyphs(src); parts = []
    for lo, hi in RANGES:
        data = b''.join(struct.pack('<' + 'H' * ROWS, *pack(g[cp])) if cp in g else b'\0' * (2 * ROWS) for cp in range(lo, hi + 1))
        parts.append('{first:0x%X,count:%d,data:"%s"}' % (lo, hi - lo + 1, base64.b64encode(data).decode()))
    open(dst, 'w').write('// Generated by tools/fonts/galmuri_bitmap.py from Galmuri11 2.40.3 (c) 2019-2025 Lee Minseo, SIL OFL 1.1.\n'
                         'globalThis.GALMURI11={rows:%d,cols:%d,ranges:[%s]};\n' % (ROWS, COLS, ','.join(parts)))
    print(dst, sum(len(p) for p in parts), 'chars')
