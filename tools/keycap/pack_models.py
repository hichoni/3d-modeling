"""Packs the ready-made keycap and keychain STLs into src/keycap-models.js for the booth's "fitted" preview.

Each mesh is stored indexed: Int16 positions in micrometres and Uint16 triangle indices, base64. For a keycap, `floor`
is the height of the pocket floor the printed plate rests on (measured from the STL: the flat upward faces inside it).
For a keychain case, `seat` is where the keycap's skirt bottom sits at rest and `plate` the switch plate's top:
plate top 10.1 + MX stem top 11.6 above the plate - the keycap's cross hole ceiling 4.2 = 17.5 (5.4 mm above the rim).
Run: python3 tools/keycap/pack_models.py
"""
import base64, json, struct, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
MODELS = {
    'keycap': ('models/keycap-base/keycap-base-socket-0.5.stl', 6.2),
    'stamp20': ('models/keycap-head/stamp-head-23.stl', 5.6),
}
CASES = {
    'case1': 'models/keycap-keychain/keycap-keychain-1.stl',
    'case2': 'models/keycap-keychain/keycap-keychain-2.stl',
}
PLATE_TOP, STEM_TOP, CROSS_CEILING, PITCH = 10.1, 11.6, 4.2, 19.05

def pack(path):
    data = (ROOT / path).read_bytes()
    count = struct.unpack_from('<I', data, 80)[0]
    index, positions, triangles = {}, [], []
    for i in range(count):
        offset = 84 + 50 * i + 12
        for k in range(3):
            key = tuple(round(v * 1000) for v in struct.unpack_from('<3f', data, offset + 12 * k))
            if key not in index:
                index[key] = len(index)
                positions.extend(key)
            triangles.append(index[key])
    assert len(index) < 65536 and all(abs(v) < 32768 for v in positions)
    blob = struct.pack(f'<{len(positions)}h', *positions) + struct.pack(f'<{len(triangles)}H', *triangles)
    return {'vertices': len(index), 'data': base64.b64encode(blob).decode()}

out = {}
for kind, (path, floor) in MODELS.items():
    out[kind] = {'source': path, 'floor': floor, **pack(path)}
for keys, (kind, path) in enumerate(CASES.items(), 1):
    out[kind] = {'source': path, 'seat': round(PLATE_TOP + STEM_TOP - CROSS_CEILING, 2), 'plate': PLATE_TOP,
                 'keys': [round((i - (keys - 1) / 2) * PITCH, 3) for i in range(keys)], **pack(path)}
(ROOT / 'src/keycap-models.js').write_text(
    '// Generated by tools/keycap/pack_models.py from the keycap STLs in models/ — do not edit.\n'
    'globalThis.KEYCAP_MODELS=' + json.dumps(out, separators=(',', ':')) + ';\n')
print({k: (v['vertices'], len(v['data'])) for k, v in out.items()})
